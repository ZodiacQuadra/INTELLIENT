function useNavState() {
  const [scrolled, setScrolled] = useState3(false);
  const [active, setActive] = useState3("");
  useEffect2(() => {
    if (isStaticRenderer2()) return void 0;
    let raf = 0;
    const update = () => {
      raf = 0;
      setScrolled(window.scrollY > 40);
      const mid = window.innerHeight * 0.5;
      let current = "";
      document.querySelectorAll("section[id]").forEach((s4) => {
        const r6 = s4.getBoundingClientRect();
        if (r6.top <= mid && r6.bottom > mid) current = s4.id;
      });
      setActive(current);
    };
    const queue = () => {
      if (!raf) raf = window.requestAnimationFrame(update);
    };
    update();
    window.addEventListener("scroll", queue, { passive: true });
    window.addEventListener("resize", queue);
    const timers = [400, 1500, 3e3].map((ms) => window.setTimeout(queue, ms));
    return () => {
      window.removeEventListener("scroll", queue);
      window.removeEventListener("resize", queue);
      timers.forEach((t5) => window.clearTimeout(t5));
      if (raf) window.cancelAnimationFrame(raf);
    };
  }, []);
  return { scrolled, active };
}

